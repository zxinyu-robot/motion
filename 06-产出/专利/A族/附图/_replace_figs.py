HEAD = "## 十一、附图说明"
NEXT = "## 十二、参考文献"


def build_section(figs):
    out = [HEAD, "", INTRO]
    for title, fname, note in figs:
        alt = title.replace(" ", "")
        out.append(f"**{title}**")
        out.append("")
        out.append(f"![{alt}](附图/{fname})")
        out.append("")
        if note:
            out.append(f"说明：{note}")
            out.append("")
    out.append("---")
    out.append("")
    out.append("")
    return "\n".join(out)


for fn, figs in DOCS.items():
    path = os.path.join(BASE, fn)
    with open(path, "r", encoding="utf-8") as f:
        text = f.read()
    a = text.index(HEAD)
    b = text.index(NEXT)
    new = build_section(figs) + NEXT
    text = text[:a] + new + text[b + len(NEXT):]
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print("updated:", fn)
